import { addDays, setHours, setMinutes, startOfDay } from "date-fns";
import { newCard } from "./srs";
import type { FolioData } from "./types";

function at(daysFromToday: number, hour = 9, minute = 0) {
  const d = setMinutes(setHours(startOfDay(new Date()), hour), minute);
  return addDays(d, daysFromToday).toISOString();
}

function session(id: string, courseId: string, daysAgo: number, hour: number, durationMin: number) {
  return {
    id,
    courseId,
    startedAt: at(-daysAgo, hour, 10),
    durationMin,
    kind: "focus" as const,
  };
}

